-- ==========================================
-- SISTEMA DE CITAS MEDICAS
-- SEGUNDO AVANCE - FUNCIONES
-- FUNCION 1: TOTAL DE CITAS POR PACIENTE
-- ==========================================

CREATE OR REPLACE FUNCTION F_TOTAL_CITAS_PACIENTE
(
    P_ID_PACIENTE IN NUMBER
)
RETURN NUMBER
AS
    V_TOTAL NUMBER;
BEGIN

    SELECT COUNT(*)
    INTO V_TOTAL
    FROM CITA
    WHERE ID_PACIENTE = P_ID_PACIENTE;

    RETURN V_TOTAL;

END;
/

-- PRUEBA DE LA FUNCION 1

SELECT F_TOTAL_CITAS_PACIENTE(1) AS TOTAL_CITAS
FROM DUAL;

