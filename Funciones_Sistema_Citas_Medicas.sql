-- ==========================================
-- FUNCION 3: OBTENER MONTO DE UN PAGO
-- ==========================================

CREATE OR REPLACE FUNCTION F_OBTENER_MONTO_PAGO
(
    P_ID_PAGO IN NUMBER
)
RETURN NUMBER
AS
    V_MONTO NUMBER;
BEGIN

    SELECT MONTO
    INTO V_MONTO
    FROM PAGO
    WHERE ID_PAGO = P_ID_PAGO;

    RETURN V_MONTO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;

END;
/

-- PRUEBA DE LA FUNCION 3

SELECT F_OBTENER_MONTO_PAGO(1) AS MONTO_PAGO
FROM DUAL;

-- ==========================================
-- FUNCION 4: OBTENER ESTADO DE UNA CITA
-- ==========================================

CREATE OR REPLACE FUNCTION F_OBTENER_ESTADO_CITA
(
    P_ID_CITA IN NUMBER
)
RETURN VARCHAR2
AS
    V_ESTADO VARCHAR2(100);
BEGIN

    SELECT ESTADO
    INTO V_ESTADO
    FROM CITA
    WHERE ID_CITA = P_ID_CITA;

    RETURN V_ESTADO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;

END;
/

-- PRUEBA DE LA FUNCION 4

SELECT F_OBTENER_ESTADO_CITA(1) AS ESTADO_CITA
FROM DUAL;