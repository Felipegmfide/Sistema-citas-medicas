-- ==========================================
-- FUNCION 3: OBTENER MONTO DE UN PAGO
-- ==========================================

CREATE OR REPLACE FUNCTION F_OBTENER_MONTO_PAGO
(
    P_ID_PAGO IN NUMBER
)
RETURN NUMBER
AS
    V_MONTO NUMBER;
BEGIN

    SELECT MONTO
    INTO V_MONTO
    FROM PAGO
    WHERE ID_PAGO = P_ID_PAGO;

    RETURN V_MONTO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;

END;
/

