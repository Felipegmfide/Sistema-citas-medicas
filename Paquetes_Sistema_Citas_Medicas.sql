SET SERVEROUTPUT ON;

CREATE OR REPLACE PACKAGE PKG_PACIENTES AS
    PROCEDURE CONSULTAR(P_ID IN NUMBER);
    FUNCTION TOTAL RETURN NUMBER;
END PKG_PACIENTES;
/
CREATE OR REPLACE PACKAGE BODY PKG_PACIENTES AS
    PROCEDURE CONSULTAR(P_ID IN NUMBER) AS
        V_ID PACIENTE.ID_PACIENTE%TYPE;
    BEGIN
        SELECT ID_PACIENTE INTO V_ID FROM PACIENTE WHERE ID_PACIENTE = P_ID;
        DBMS_OUTPUT.PUT_LINE('REGISTRO: ' || V_ID);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('REGISTRO NO ENCONTRADO');
    END CONSULTAR;
    FUNCTION TOTAL RETURN NUMBER AS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_TOTAL FROM PACIENTE;
        RETURN V_TOTAL;
    END TOTAL;
END PKG_PACIENTES;
/

