-- TRIGGER 3: VALIDAR HORARIO DEL MEDICO
CREATE OR REPLACE TRIGGER TR_VALIDAR_HORARIO_MEDICO
BEFORE INSERT OR UPDATE OF HORA_INICIO, HORA_FIN
ON HORARIO
FOR EACH ROW
BEGIN
    IF :NEW.HORA_INICIO IS NULL
       OR :NEW.HORA_FIN IS NULL
       OR NOT REGEXP_LIKE(:NEW.HORA_INICIO,
          '^([01][0-9]|2[0-3]):[0-5][0-9]$')
       OR NOT REGEXP_LIKE(:NEW.HORA_FIN,
          '^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN

        RAISE_APPLICATION_ERROR(
            -20003,
            'FORMATO DE HORARIO NO VALIDO'
        );
    END IF;

    IF :NEW.HORA_FIN <= :NEW.HORA_INICIO THEN
        RAISE_APPLICATION_ERROR(
            -20004,
            'LA HORA FINAL DEBE SER MAYOR A LA INICIAL'
        );
    END IF;
END;
/

-- TRIGGER 4: VALIDAR MONTO DEL PAGO
CREATE OR REPLACE TRIGGER TR_VALIDAR_MONTO_PAGO
BEFORE INSERT OR UPDATE OF MONTO
ON PAGO
FOR EACH ROW
BEGIN
    IF :NEW.MONTO IS NULL OR :NEW.MONTO < 0 THEN
        RAISE_APPLICATION_ERROR(
            -20005,
            'EL MONTO DEL PAGO NO PUEDE SER NEGATIVO O NULO'
        );
    END IF;
END;
/

-- TRIGGER: VALIDAR FECHA DE NACIMIENTO
CREATE OR REPLACE TRIGGER TR_VALIDAR_FECHA_NACIMIENTO
BEFORE INSERT OR UPDATE OF FECHA_NACIMIENTO
ON PACIENTE
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_NACIMIENTO IS NOT NULL
       AND :NEW.FECHA_NACIMIENTO > TRUNC(SYSDATE) THEN

        RAISE_APPLICATION_ERROR(
            -20006,
            'LA FECHA DE NACIMIENTO NO PUEDE SER FUTURA'
        );
    END IF;
END;
