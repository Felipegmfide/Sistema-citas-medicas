CREATE OR REPLACE VIEW V_PACIENTES_USUARIOS AS
SELECT
    P.ID_PACIENTE,
    P.IDENTIFICACION,
    P.NOMBRE,
    P.APELLIDO1,
    P.APELLIDO2,
    P.TELEFONO,
    U.CORREO,
    P.ESTADO
FROM PACIENTE P
LEFT JOIN USUARIO U
ON P.ID_USUARIO = U.ID_USUARIO;
/

-- VISTA 7: CITAS POR MEDICO
CREATE OR REPLACE VIEW V_CITAS_POR_MEDICO AS
SELECT
    C.ID_CITA,
    M.ID_MEDICO,
    M.NOMBRE AS NOMBRE_MEDICO,
    P.NOMBRE AS NOMBRE_PACIENTE,
    C.FECHA_CITA,
    C.HORA_CITA,
    C.MOTIVO,
    C.ESTADO
FROM CITA C
INNER JOIN MEDICO M
ON C.ID_MEDICO = M.ID_MEDICO
INNER JOIN PACIENTE P
ON C.ID_PACIENTE = P.ID_PACIENTE;
/

