-- 11. CURSOR RELACION MEDICO - ESPECIALIDAD
DECLARE
    CURSOR C_MEDICO_ESPECIALIDAD IS
        SELECT M.ID_MEDICO, M.NOMBRE AS NOMBRE_MEDICO,
               E.ID_ESPECIALIDAD, E.NOMBRE AS NOMBRE_ESPECIALIDAD
        FROM MEDICO_ESPECIALIDAD ME
        JOIN MEDICO M ON M.ID_MEDICO = ME.ID_MEDICO
        JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD = ME.ID_ESPECIALIDAD
        ORDER BY M.ID_MEDICO, E.ID_ESPECIALIDAD;
    V_FILA C_MEDICO_ESPECIALIDAD%ROWTYPE;
BEGIN
    OPEN C_MEDICO_ESPECIALIDAD;
    LOOP
        FETCH C_MEDICO_ESPECIALIDAD INTO V_FILA;
        EXIT WHEN C_MEDICO_ESPECIALIDAD%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('MEDICO-ESPECIALIDAD: ' || V_FILA.NOMBRE_MEDICO || ' - ' || V_FILA.NOMBRE_ESPECIALIDAD);
    END LOOP;
    CLOSE C_MEDICO_ESPECIALIDAD;
END;
