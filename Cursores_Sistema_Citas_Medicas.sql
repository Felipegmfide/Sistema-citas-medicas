SET SERVEROUTPUT ON;

-- CURSOR CITAS
DECLARE
    CURSOR C_CITAS IS
        SELECT ID_CITA, ID_PACIENTE, ESTADO FROM CITA ORDER BY ID_CITA;
    V_FILA C_CITAS%ROWTYPE;
BEGIN
    OPEN C_CITAS;
    LOOP
        FETCH C_CITAS INTO V_FILA;
        EXIT WHEN C_CITAS%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('CITAS: ' || V_FILA.ID_CITA);
    END LOOP;
    CLOSE C_CITAS;
END;
/

