-- ==========================================
-- SISTEMA DE CITAS MEDICAS
-- SEGUNDO AVANCE - PROCEDIMIENTOS
-- PROCEDIMIENTO 1: ACTUALIZAR ESTADO CITA
-- ==========================================

CREATE OR REPLACE PROCEDURE PD_ACTUALIZAR_ESTADO_CITA
(
    P_ID_CITA IN NUMBER,
    P_ESTADO IN VARCHAR2
)
AS
BEGIN

    UPDATE CITA
    SET ESTADO = P_ESTADO
    WHERE ID_CITA = P_ID_CITA;

    DBMS_OUTPUT.PUT_LINE('Cita actualizada correctamente');

END;
/

-- PRUEBA DEL PROCEDIMIENTO 1

BEGIN
    PD_ACTUALIZAR_ESTADO_CITA(1, 'CONFIRMADA');
END;
/

-- VERIFICAR EL CAMBIO
SELECT ID_CITA, ESTADO
FROM CITA
WHERE ID_CITA = 1;

