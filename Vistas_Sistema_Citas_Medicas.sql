-- VISTA 1: PACIENTES ACTIVOS
CREATE OR REPLACE VIEW V_PACIENTES_ACTIVOS AS
SELECT ID_PACIENTE,
       IDENTIFICACION,
       NOMBRE,
       APELLIDO1,
       APELLIDO2,
       TELEFONO
FROM PACIENTE
WHERE ESTADO = 'ACTIVO';


-- VISTA 2: MEDICOS ACTIVOS
CREATE OR REPLACE VIEW V_MEDICOS_ACTIVOS AS
SELECT ID_MEDICO,
       IDENTIFICACION,
       NOMBRE,
       APELLIDO1,
       APELLIDO2,
       TELEFONO
FROM MEDICO
WHERE ESTADO = 'ACTIVO';


-- VISTA 3: DETALLE DE CITAS
CREATE OR REPLACE VIEW V_CITAS_DETALLE AS
SELECT C.ID_CITA,
       P.NOMBRE AS PACIENTE,
       M.NOMBRE AS MEDICO,
       C.FECHA_CITA,
       C.HORA_CITA,
       C.MOTIVO,
       C.ESTADO
FROM CITA C
INNER JOIN PACIENTE P
    ON C.ID_PACIENTE = P.ID_PACIENTE
INNER JOIN MEDICO M
    ON C.ID_MEDICO = M.ID_MEDICO;


-- VISTA 4: MEDICOS Y ESPECIALIDADES
CREATE OR REPLACE VIEW V_MEDICOS_ESPECIALIDADES AS
SELECT M.ID_MEDICO,
       M.NOMBRE AS MEDICO,
       E.NOMBRE AS ESPECIALIDAD
FROM MEDICO M
INNER JOIN MEDICO_ESPECIALIDAD ME
    ON M.ID_MEDICO = ME.ID_MEDICO
INNER JOIN ESPECIALIDAD E
    ON ME.ID_ESPECIALIDAD = E.ID_ESPECIALIDAD;


-- VISTA 5: PAGOS DE CITAS
CREATE OR REPLACE VIEW V_PAGOS_CITAS AS
SELECT PG.ID_PAGO,
       C.ID_CITA,
       PG.MONTO,
       PG.METODO_PAGO,
       PG.FECHA_PAGO,
       PG.ESTADO
FROM PAGO PG
INNER JOIN CITA C
    ON PG.ID_CITA = C.ID_CITA;
    
    
