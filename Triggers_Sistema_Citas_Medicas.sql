SET SERVEROUTPUT ON;

-- VALIDAR HORA DE CITA
CREATE OR REPLACE TRIGGER TR_VALIDAR_HORA_CITA
BEFORE INSERT OR UPDATE OF HORA_CITA ON CITA
FOR EACH ROW
BEGIN
    IF :NEW.HORA_CITA IS NULL OR
       NOT REGEXP_LIKE(:NEW.HORA_CITA, '^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN
        RAISE_APPLICATION_ERROR(-20001, 'HORA DE CITA NO VALIDA');
    END IF;
END;
/

-- GUARDAR HISTORIAL AL CAMBIAR ESTADO
CREATE OR REPLACE TRIGGER TR_HISTORIAL_ESTADO_CITA
AFTER UPDATE OF ESTADO ON CITA
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO <> :NEW.ESTADO THEN
        INSERT INTO HISTORIAL_CITA
            (ID_HISTORIAL, ID_CITA, ACCION, DESCRIPCION, FECHA_CAMBIO)
        VALUES
            (SEQ_HISTORIAL.NEXTVAL, :NEW.ID_CITA, 'CAMBIO ESTADO',
             'DE ' || :OLD.ESTADO || ' A ' || :NEW.ESTADO, SYSTIMESTAMP);
    END IF;
END;
/

-- EVITAR MONTOS NEGATIVOS
CREATE OR REPLACE TRIGGER TR_VALIDAR_MONTO_PAGO
BEFORE INSERT OR UPDATE OF MONTO ON PAGO
FOR EACH ROW
BEGIN
    IF :NEW.MONTO IS NULL OR :NEW.MONTO < 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'MONTO NO VALIDO');
    END IF;
END;
/
